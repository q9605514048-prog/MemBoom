import {readFile,writeFile,mkdir} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import {resolve} from 'node:path';
const root=fileURLToPath(new URL('../../',import.meta.url));
const raw=await readFile(resolve(root,'locales/en.json'),'utf8'),messages=JSON.parse(raw);
for(const [key,value] of Object.entries(messages)){
 if(typeof value!=='string'||!value.trim())throw Error('Empty translation: '+key);
 const slots=v=>[...v.matchAll(/\{\d+\}/g)].map(x=>x[0]).sort().join(',');
 if(slots(key)!==slots(value))throw Error('Translation placeholders do not match: '+key);
}
const core=await readFile(resolve(root,'Application/scripts/i18n-core.js'),'utf8');
await writeFile(resolve(root,'Application/scripts/i18n.js'),'// Generated by tools/i18n/build.mjs\nglobalThis.MemBoomTranslations='+JSON.stringify(messages)+';\n'+core);
const assets=resolve(root,'clients/android/app/src/main/assets');await mkdir(assets,{recursive:true});await writeFile(resolve(assets,'en.json'),raw);
console.log(`Built ${Object.keys(messages).length} English interface translations for website and Android.`);
